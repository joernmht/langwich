#!/usr/bin/env python3
"""Regenerate ``docs/quality.md`` from the design rubric in ``src/langwich/quality.py``.

    python scripts/export_rubric.py           # rewrite the file
    python scripts/export_rubric.py --check   # exit 1 if the file is out of date

The rules, the task-kind ranges and the level limits are defined once, in
``langwich.quality``; the Markdown file is the readable copy. ``tests/test_quality.py``
runs the same comparison as ``--check``, so the page cannot drift from the code.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DOC_PATH = ROOT / "docs" / "quality.md"

INTRO = """\
# The design rubric

<!-- Generated by scripts/export_rubric.py from src/langwich/quality.py. Do not edit by hand. -->

`langwich validate FILE` answers one question: will this sheet work? The file matches the
contract, nothing is broken, no answer is given away. The design rubric answers the next one —
is it a well-made lesson? — as far as that can be **measured**.

```bash
langwich validate data/night_trains_en_de.json --quality            # the report, then the findings
langwich validate data/night_trains_en_de.json --quality --prompt   # … as a repair prompt for the AI
langwich validate data/night_trains_en_de.json --quality --strict   # exit status 1 on any finding
langwich validate data/night_trains_en_de.json --quality --json     # findings and measures as JSON
```

Every rule is a pure function of the worksheet JSON: no AI reads the sheet, nothing is fetched,
nothing is random. The same file gets the same findings, in the same order, on every machine.
That is what makes the rubric usable as a test.

## What it is for

- **A worksheet you just made.** Run it with `--quality`. A finding says where (a JSON pointer),
  what is wrong and what to do; `--prompt` hands all of them to the AI that wrote the file.
- **A change to the brief.** Write the same story with the old and the new brief and compare the
  findings and the measures (`--json` prints both): words per sentence, share of direct speech,
  number of items, how many tasks can be checked against the key.
- **A new kind of task.** `KIND_DESIGN` in `langwich.quality` holds one entry per task kind: what
  is counted, how many of it one task should have, and how the learner checks the answer. A kind
  without an entry fails the tests, and so does an entry that no real task lives up to. A new
  exercise concept has to say what good looks like before it ships.
- **The bundled examples.** `tests/test_quality.py` holds every example to every rule. Findings
  that are known and tolerated are listed there in `ACCEPTED`, each with a reason; the test fails
  on a finding that is not listed, and on a listed finding that no longer occurs. So the list can
  only shrink. To raise the bar, add a rule, give it a broken example in `MUTANTS` (a rule without
  one fails the suite), and fix or list what it finds.

## What it cannot see

Whether the facts are true. Whether the language is natural and right for the level. Whether the
reader wants to know how the story ends. No deterministic rule can judge these; they stay with
the author and the reviewer (the `/langwich` command reviews them in step 5). A sheet without
findings is well built, not necessarily good.
"""

SECTIONS = {
    "story": (
        "Story",
        "The shape of the story: beats, a protagonist who is there from the first scene to the "
        "last, direct speech, scenes of similar weight, sentences that fit the level, facts "
        "beside the story rather than inside it.",
    ),
    "lesson": (
        "Lesson",
        "The arc of the sheet: every phase present, every scene checked, the key words "
        "pre-taught, recycled and finally written by the learner, every grammar point "
        "practised, a mix of task kinds.",
    ),
    "items": (
        "Items",
        "The craft of the single task: enough items and not too many, true/false with both "
        "kinds, options of similar length, spare words in every word box, nothing in the task "
        "that shows its own answer, room to write.",
    ),
}

RESPONSES = {
    "closed": "one right answer in the key",
    "guided": "a model answer to compare with",
    "open": "nothing to compare (the learner's own find or drawing)",
}


def rubric_text() -> str:
    """docs/quality.md as the exporter writes it."""
    sys.path.insert(0, str(ROOT / "src"))
    from langwich import quality
    from langwich.prompt import LEVELS

    out = [INTRO]
    out.append(f"## The {len(quality.RULES)} rules\n")
    out.append(
        "Where a number comes from the authoring brief (`langwich prompt`), the reason says "
        "so; the tests hold those numbers against the brief, so the two cannot drift apart. The "
        "other rules are common item-writing practice.\n"
    )
    for dimension in quality.DIMENSIONS:
        title, lead = SECTIONS[dimension]
        rules = [(c, r) for c, r in quality.RULES.items() if r.dimension == dimension]
        out.append(f"### {title} ({len(rules)})\n\n{lead}\n")
        out.append("| Rule | What good looks like | Why |\n|---|---|---|")
        out.extend(f"| `{code}` | {rule.title} | {rule.why} |" for code, rule in rules)
        out.append("")

    out.append("## Task kinds\n")
    out.append(
        "What is counted in a task of each kind, how many of it a task should have "
        "(`item-count`), and how the learner checks the work.\n"
    )
    out.append("| Kind | Counted | Sensible range | The learner checks against |\n|---|---|---|---|")
    for kind, design in quality.KIND_DESIGN.items():
        low, high = design.items
        span = str(low) if low == high else f"{low}–{high}"
        out.append(f"| `{kind}` | {design.unit} | {span} | {RESPONSES[design.response]} |")
    out.append("")

    out.append("## Level limits\n")
    out.append(
        "`sentence-length` and `writing-scaffold` scale with the CEFR level. The sentence "
        "limits are the rubric's own table: from A1 to B1 they are the upper ends of the "
        "brief's level table, and a test holds them against it; beyond B1 the brief gives no "
        "numbers. The writing range is read from the brief; a task may leave it by half at "
        "the lower end and by half at the upper end before the rule reports it.\n"
    )
    out.append(
        "| Level | Words per sentence (mean, at most) | Longest sentence (at most) | "
        "Writing task (words) |\n|---|---|---|---|"
    )
    for level, spec in LEVELS.items():
        cap = quality.SENTENCE_WORDS[level]
        low, high = spec.writing
        out.append(f"| {level} | {cap} | {2 * cap} | {low}–{high} |")
    out.append("")
    return "\n".join(out)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=(__doc__ or "").splitlines()[0])
    parser.add_argument("--check", action="store_true",
                        help="do not write; exit 1 if docs/quality.md is out of date")
    args = parser.parse_args(argv)
    text = rubric_text()
    rel = DOC_PATH.relative_to(ROOT)
    if args.check:
        current = DOC_PATH.read_text(encoding="utf-8") if DOC_PATH.exists() else ""
        if current != text:
            print(f"{rel} is out of date; run: python scripts/export_rubric.py", file=sys.stderr)
            return 1
        print(f"{rel} is up to date.")
        return 0
    DOC_PATH.write_text(text, encoding="utf-8")
    print(f"Wrote {rel}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
