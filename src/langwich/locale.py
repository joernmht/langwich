#: Quotation marks around words quoted from the story in the answer key, by
#: the language of the words (French with its no-break spaces); other
#: languages get « ».
QUOTE_MARKS: dict[str, tuple[str, str]] = {
    "de": ("„", "“"), "fr": ("«\u00a0", "\u00a0»"), "en": ("“", "”"), "nl": ("“", "”"),
    "es": ("«", "»"), "it": ("«", "»"), "pt": ("«", "»"), "pl": ("„", "”"), "cs": ("„", "“"),
    "sk": ("„", "“"), "hu": ("„", "”"), "ro": ("„", "”"), "sv": ("”", "”"), "fi": ("”", "”"),
    "da": ("»", "«"), "tr": ("“", "”"), "ja": ("「", "」"), "zh": ("“", "”"), "ko": ("“", "”"),
}


def base_lang(code: str) -> str:
    return code.split("-", 1)[0].lower()


def quoted(text: str, lang: str) -> str:
    """``text`` in the quotation marks of ``lang`` (see :data:`QUOTE_MARKS`)."""
    opening, closing = QUOTE_MARKS.get(base_lang(lang), ("«", "»"))
    return f"{opening}{text}{closing}"


def t(key: str, lang: str, overrides: Mapping[str, str] | None = None, **fmt: object) -> str:
    """Look up a furniture string for ``lang``; ``overrides`` (the
    worksheet's ``ui`` map) win, English is the last resort."""
    text = None
    if overrides:
        text = overrides.get(key)
    if text is None:
        text = STRINGS.get(base_lang(lang), {}).get(key)
    if text is None:
        text = STRINGS["en"][key]
    if not fmt:
        return text
    try:
        return text.format(**fmt)
    except (KeyError, IndexError, ValueError):
        # an override with stray or unknown {placeholders}: use the built-in text
        builtin = STRINGS.get(base_lang(lang), {}).get(key) or STRINGS["en"][key]
        return builtin.format(**fmt)


def direction(code: str) -> str:
    """``"rtl"`` for languages written right to left, else ``"ltr"``."""
    return "rtl" if base_lang(code) in RTL_LANGUAGES else "ltr"


def endonym(code: str) -> str:
    return ENDONYMS.get(base_lang(code), code)


def missing_keys(lang: str, overrides: Mapping[str, str] | None = None) -> list[str]:
    """Keys that would fall back to English for this source language."""
    if base_lang(lang) in STRINGS:
        return []
    have = set(overrides or {})
    return [k for k in STRINGS["en"] if k not in have]
