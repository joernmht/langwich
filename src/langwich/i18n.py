def localize(en_text: str, source_lang: str) -> str:
    """Translate an instruction string into the learner's source language."""
    if source_lang == "en":
        return en_text
    lang_table = INSTRUCTION_TRANSLATIONS.get(source_lang)
    if lang_table:
        return lang_table.get(en_text, en_text)
    return en_text


def localize_fmt(en_template: str, source_lang: str, **kwargs: str) -> str:
    """Localize a template string, then substitute its placeholders."""
    return localize(en_template, source_lang).format(**kwargs)


def lang_name(lang_code: str, in_language: str) -> str:
    """Name of a language, written in another language."""
    names = LANG_NAMES.get(in_language, LANG_NAMES["en"])
    return names.get(lang_code, lang_code)


def question_words(target_lang: str) -> list[str]:
    return QUESTION_WORDS.get(target_lang, QUESTION_WORDS["en"])


def connector_words(target_lang: str) -> list[str]:
    return CONNECTOR_WORDS.get(target_lang, CONNECTOR_WORDS["en"])


def day_names(target_lang: str) -> list[str]:
    return DAY_NAMES.get(target_lang, DAY_NAMES["en"])
